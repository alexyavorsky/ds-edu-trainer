# Примеры к статье pandas/rolling.

# %% setup
days = pd.date_range("2024-03-01", periods=8, freq="D")
visits = pd.Series([120, 135, 128, 150, 162, 90, 85, 140], index=days, name="visits")

# %% rolling-mean
visits.rolling(3).mean().round(1)                 # среднее за 3 дня; первые 2 — NaN
# ─── вывод ───
# 2024-03-01      NaN
# 2024-03-02      NaN
# 2024-03-03    127.7
# 2024-03-04    137.7
# 2024-03-05    146.7
# 2024-03-06    134.0
# 2024-03-07    112.3
# 2024-03-08    105.0
# Freq: D, Name: visits, dtype: float64

# %% min-periods
visits.rolling(3, min_periods=1).mean().round(1)  # считать, даже если данных меньше окна
# ─── вывод ───
# 2024-03-01    120.0
# 2024-03-02    127.5
# 2024-03-03    127.7
# 2024-03-04    137.7
# 2024-03-05    146.7
# 2024-03-06    134.0
# 2024-03-07    112.3
# 2024-03-08    105.0
# Freq: D, Name: visits, dtype: float64

# %% center
visits.rolling(3, center=True).mean().round(1)    # окно вокруг дня, а не до него
# ─── вывод ───
# 2024-03-01      NaN
# 2024-03-02    127.7
# 2024-03-03    137.7
# 2024-03-04    146.7
# 2024-03-05    134.0
# 2024-03-06    112.3
# 2024-03-07    105.0
# 2024-03-08      NaN
# Freq: D, Name: visits, dtype: float64

# %% time-window
gaps = visits.drop(visits.index[[2, 3]])           # два дня без данных
gaps.rolling("3D").sum()                          # окно по времени, а не по числу строк
# ─── вывод ───
# 2024-03-01    120.0
# 2024-03-02    255.0
# 2024-03-05    162.0
# 2024-03-06    252.0
# 2024-03-07    337.0
# 2024-03-08    315.0
# Name: visits, dtype: float64

# %% expanding
pd.DataFrame({"visits": visits, "max_so_far": visits.expanding().max(), "mean_so_far": visits.expanding().mean().round(1)})
# ─── вывод ───
#             visits  max_so_far  mean_so_far
# 2024-03-01     120       120.0        120.0
# 2024-03-02     135       135.0        127.5
# 2024-03-03     128       135.0        127.7
# 2024-03-04     150       150.0        133.2
# 2024-03-05     162       162.0        139.0
# 2024-03-06      90       162.0        130.8
# 2024-03-07      85       162.0        124.3
# 2024-03-08     140       162.0        126.2

# %% ewm
visits.ewm(span=3, adjust=False).mean().round(1)  # недавние дни весят больше
# ─── вывод ───
# 2024-03-01    120.0
# 2024-03-02    127.5
# 2024-03-03    127.8
# 2024-03-04    138.9
# 2024-03-05    150.4
# 2024-03-06    120.2
# 2024-03-07    102.6
# 2024-03-08    121.3
# Freq: D, Name: visits, dtype: float64

# %% agg
visits.rolling(3).agg(["min", "max"])
# ─── вывод ───
#               min    max
# 2024-03-01    NaN    NaN
# 2024-03-02    NaN    NaN
# 2024-03-03  120.0  135.0
# 2024-03-04  128.0  150.0
# 2024-03-05  128.0  162.0
# 2024-03-06   90.0  162.0
# 2024-03-07   85.0  162.0
# 2024-03-08   85.0  140.0

# %% groups
sales = pd.DataFrame({
    "shop": ["A", "A", "A", "B", "B", "B"],
    "cups": [10, 20, 30, 5, 15, 25],
})
sales.groupby("shop")["cups"].rolling(2).mean()   # окна не переходят через границу групп
# ─── вывод ───
# shop
# A     0     NaN
#       1    15.0
#       2    25.0
# B     3     NaN
#       4    10.0
#       5    20.0
# Name: cups, dtype: float64
