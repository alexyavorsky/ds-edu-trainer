# Примеры к статье numpy/repeat-tile.

# %% setup
m = np.array([[1, 2],
              [3, 4]])

# %% basic
week = np.array([1, 2, 3])
print(np.repeat(week, 2))       # каждый элемент по 2 раза
np.tile(week, 2)                # весь массив 2 раза
# ─── вывод ───
# [1 1 2 2 3 3]
# array([1, 2, 3, 1, 2, 3])

# %% counts
np.repeat(np.array(["чай", "кофе", "сок"]), [3, 1, 2])   # у каждого своё число повторов
# ─── вывод ───
# array(['чай', 'чай', 'чай', 'кофе', 'сок', 'сок'], dtype='<U4')

# %% repeat-axis
print(np.repeat(m, 2, axis=0))  # каждая строка дважды
np.repeat(m, 2)                 # без axis — массив вытягивается в строку
# ─── вывод ───
# [[1 2]
#  [1 2]
#  [3 4]
#  [3 4]]
# array([1, 1, 2, 2, 3, 3, 4, 4])

# %% tile-2d
np.tile(m, (2, 3))              # 2 раза вниз, 3 раза вправо
# ─── вывод ───
# array([[1, 2, 1, 2, 1, 2],
#        [3, 4, 3, 4, 3, 4],
#        [1, 2, 1, 2, 1, 2],
#        [3, 4, 3, 4, 3, 4]])

# %% no-broadcast
prices = np.array([10, 20, 30])
qty = np.array([[1], [2]])
print(prices * np.tile(qty, (1, 3)))   # tile не нужен…
prices * qty                           # …транслирование делает то же без копий
# ─── вывод ───
# [[10 20 30]
#  [20 40 60]]
# array([[10, 20, 30],
#        [20, 40, 60]])
