# Примеры к статье numpy/flip-roll.

# %% setup
m = np.array([[1, 2, 3],
              [4, 5, 6]])

# %% flip
print(np.flip(np.array([1, 2, 3, 4])))
print(np.flip(m, axis=0))       # строки в обратном порядке (flipud)
np.flip(m, axis=1)              # столбцы в обратном порядке (fliplr)
# ─── вывод ───
# [4 3 2 1]
# [[4 5 6]
#  [1 2 3]]
# array([[3, 2, 1],
#        [6, 5, 4]])

# %% flip-all
np.flip(m)                      # по всем осям сразу
# ─── вывод ───
# array([[6, 5, 4],
#        [3, 2, 1]])

# %% roll
days = np.array(["пн", "вт", "ср", "чт", "пт"])
print(np.roll(days, 1))         # сдвиг вправо, последний уходит в начало
np.roll(days, -2)               # сдвиг влево
# ─── вывод ───
# ['пт' 'пн' 'вт' 'ср' 'чт']
# array(['ср', 'чт', 'пт', 'пн', 'вт'], dtype='<U2')

# %% roll-axis
print(np.roll(m, 1, axis=1))    # по столбцам
np.roll(m, 1)                   # без axis — как по вытянутому массиву
# ─── вывод ───
# [[3 1 2]
#  [6 4 5]]
# array([[6, 1, 2],
#        [3, 4, 5]])

# %% rot90
print(np.rot90(m))              # на 90° против часовой стрелки
np.rot90(m, k=-1)               # по часовой
# ─── вывод ───
# [[3 6]
#  [2 5]
#  [1 4]]
# array([[4, 1],
#        [5, 2],
#        [6, 3]])

# %% roll-not-shift
prices = np.array([10, 11, 13, 12])
np.roll(prices, 1)              # «вчерашняя цена» для первого дня взялась из последнего
# ─── вывод ───
# array([12, 10, 11, 13])
