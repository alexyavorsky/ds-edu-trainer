# Примеры к статье numpy/indexing-nd.

# %% setup
# температура: 3 города (строки) × 5 дней (столбцы)
temps = np.array([[12, 14, 15, 13, 11],
                  [ 8,  9, 11, 10,  7],
                  [20, 22, 21, 19, 18]])

# %% element
print(temps[1, 2])      # город 1, день 2
temps[-1, -1]           # последний город, последний день
# ─── вывод ───
# 11
# np.int64(18)

# %% row-col
print(temps[0])         # строка — все дни города 0
temps[:, 2]             # столбец — все города в день 2
# ─── вывод ───
# [12 14 15 13 11]
# array([15, 11, 21])

# %% block
print(temps[:2, 1:4])   # два первых города, дни 1–3
temps[:, ::2]           # каждый второй день
# ─── вывод ───
# [[14 15 13]
#  [ 9 11 10]]
# array([[12, 15, 11],
#        [ 8, 11,  7],
#        [20, 21, 18]])

# %% keep-dims
print(temps[:, 2].shape)     # столбец превратился в вектор
temps[:, 2:3].shape          # срез длины 1 сохраняет ось
# ─── вывод ───
# (3,)
# (3, 1)

# %% ellipsis
cube = np.arange(24).reshape(2, 3, 4)
print(cube[..., 0])     # то же, что cube[:, :, 0]
cube[0, ...].shape
# ─── вывод ───
# [[ 0  4  8]
#  [12 16 20]]
# (3, 4)

# %% assign
temps[1, :] = 0          # обнулить строку
temps[:, 0] = [1, 2, 3]  # записать столбец
temps
# ─── вывод ───
# array([[ 1, 14, 15, 13, 11],
#        [ 2,  0,  0,  0,  0],
#        [ 3, 22, 21, 19, 18]])

# %% chained
print(temps[:, 0])      # столбец 0
temps[:][0]             # это НЕ столбец: [:] — все строки, затем [0] — первая строка
# ─── вывод ───
# [12  8 20]
# array([12, 14, 15, 13, 11])
